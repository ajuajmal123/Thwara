-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 2. TABLES
-- ==============================================================================

-- 2.1 AUTHORS
CREATE TABLE IF NOT EXISTS public.authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    photo TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.2 ARTICLES
CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    subheading TEXT,
    author_name TEXT NOT NULL,
    domain TEXT DEFAULT 'Literature',
    date TEXT NOT NULL,
    cover_image TEXT,
    additional_images JSONB DEFAULT '[]'::jsonb,
    author_photo TEXT,
    author_description TEXT,
    reference TEXT,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.3 FICTIONS
CREATE TABLE IF NOT EXISTS public.fictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    subheading TEXT,
    author_name TEXT NOT NULL,
    genre TEXT DEFAULT 'Story', -- 'Story', 'Poem', 'Cartoon'
    date TEXT NOT NULL,
    cover_image TEXT,
    additional_images JSONB DEFAULT '[]'::jsonb,
    author_photo TEXT,
    author_description TEXT,
    notes TEXT,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.4 FOLKLORES
CREATE TABLE IF NOT EXISTS public.folklores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    subheading TEXT,
    narrator_name TEXT NOT NULL,
    category TEXT DEFAULT 'Oral Histories', -- 'Oral Histories', 'Folk Practices', 'Folk Literature', 'Myths', 'Legends', 'Field notes'
    date TEXT NOT NULL,
    cover_image TEXT,
    additional_images JSONB DEFAULT '[]'::jsonb,
    narrator_photo TEXT,
    narrator_description TEXT,
    reference TEXT,
    spotify_url TEXT,
    content TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.5 WEBZINES
CREATE TABLE IF NOT EXISTS public.webzines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE,
    title TEXT NOT NULL,
    webzine_name TEXT,
    issue_number TEXT,
    domain TEXT DEFAULT 'Visual Essay',
    date TEXT NOT NULL,
    cover_image TEXT,
    work_name TEXT,
    excerpt TEXT,
    description TEXT,
    author_name TEXT,
    additional_images JSONB DEFAULT '[]'::jsonb,
    articles JSONB DEFAULT '[]'::jsonb,
    fictions JSONB DEFAULT '[]'::jsonb,
    folklores JSONB DEFAULT '[]'::jsonb,
    tellings JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.6 TELLINGS (Audio, Stories, Podcasts, Interviews)
CREATE TABLE IF NOT EXISTS public.tellings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    cover_image TEXT,
    category TEXT NOT NULL, -- 'Stories', 'Interview', 'Podcast'
    spotify_url TEXT,
    audio_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2.7 SUBMISSIONS (User uploaded articles/pitches)
CREATE TABLE IF NOT EXISTS public.submissions (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    author_name TEXT NOT NULL,
    email TEXT,
    title TEXT NOT NULL,
    google_drive_link TEXT,
    document_url TEXT,
    document_name TEXT,
    agreed_to_privacy BOOLEAN DEFAULT TRUE,
    status TEXT DEFAULT 'Pending', -- 'Pending', 'Under Review', 'Accepted', 'Rejected'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 3. INDEXES FOR PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_articles_slug ON public.articles(slug);
CREATE INDEX IF NOT EXISTS idx_articles_domain ON public.articles(domain);
CREATE INDEX IF NOT EXISTS idx_fictions_slug ON public.fictions(slug);
CREATE INDEX IF NOT EXISTS idx_folklores_slug ON public.folklores(slug);
CREATE INDEX IF NOT EXISTS idx_submissions_created_at ON public.submissions(created_at DESC);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================

-- Enable RLS on all tables
ALTER TABLE public.authors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fictions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folklores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.webzines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tellings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.submissions ENABLE ROW LEVEL SECURITY;

-- Public read policies for content
CREATE POLICY "Public read on authors" ON public.authors FOR SELECT USING (true);
CREATE POLICY "Public read on articles" ON public.articles FOR SELECT USING (true);
CREATE POLICY "Public read on fictions" ON public.fictions FOR SELECT USING (true);
CREATE POLICY "Public read on folklores" ON public.folklores FOR SELECT USING (true);
CREATE POLICY "Public read on webzines" ON public.webzines FOR SELECT USING (true);
CREATE POLICY "Public read on tellings" ON public.tellings FOR SELECT USING (true);

-- Submissions policy: Anyone can submit (insert), only authenticated admins can select/update
CREATE POLICY "Public insert on submissions" ON public.submissions FOR INSERT WITH CHECK (true);
CREATE POLICY "Admin view submissions" ON public.submissions FOR SELECT USING (auth.role() = 'authenticated');

-- ==============================================================================
-- 5. STORAGE BUCKETS SETUP
-- ==============================================================================
-- Create 'media' bucket for public images
INSERT INTO storage.buckets (id, name, public)
VALUES ('media', 'media', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Create 'submissions' bucket for uploaded documents
INSERT INTO storage.buckets (id, name, public)
VALUES ('submissions', 'submissions', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage policies: Public read for media bucket
CREATE POLICY "Public read media"
ON storage.objects FOR SELECT
USING (bucket_id = 'media');

-- Storage policies: Anyone can upload submission documents
CREATE POLICY "Public upload submissions"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'submissions');

-- Storage policies: Public read submissions documents (if needed)
CREATE POLICY "Public read submissions"
ON storage.objects FOR SELECT
USING (bucket_id = 'submissions');

